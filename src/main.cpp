// Rolling frame-time history for the FPS overlay.
struct FrameStats {
    static constexpr int N = 180;
    float ms[N] = {};
    int   idx = 0;
    void  push(float v) { ms[idx] = v; idx = (idx + 1) % N; }
    float avg() const { float s = 0; for (float v : ms) s += v; return s / N; }
    float maxv() const { float m = 0; for (float v : ms) m = std::max(m, v); return m; }
};

static double pcSeconds(Uint64 a, Uint64 b) {
    return (double)(b - a) / (double)SDL_GetPerformanceFrequency();
}

// ImPlot tick formatter for the absolute-time (LSL clock) x-axis. LSL timestamps run large
// (lsl_local_clock is uptime-based — easily 1e5+ on a machine that's been up a while, and macOS
// starts higher than a fresh Linux boot), which ImPlot's default "%g" renders as "1.2e5". Force
// fixed-point and trim trailing zeros so a 0.5 s grid reads "523456.5", not "523456.500" or "5.2e5".
static int fmtTimeAxis(double value, char* buff, int size, void*) {
    int n = snprintf(buff, size, "%.3f", value);
    if (n <= 0 || n >= size) return n;
    bool hasDot = false;
    for (int i = 0; i < n; ++i) if (buff[i] == '.') { hasDot = true; break; }
    if (hasDot) {
        while (n > 0 && buff[n - 1] == '0') buff[--n] = '\0';
        if (n > 0 && buff[n - 1] == '.') buff[--n] = '\0';
    }
    return n;
}

// ImPlot's default locator sizes the tick count by plot width alone (about one major per 400 px),
// labels the minor ticks too, and hides every other label only once when they crowd. LSL
// timestamps are six or more digits, so a narrow plot (a bottom-row spectrogram) still overlapped
// them. This one spaces the majors by the measured label width and leaves the minors unlabeled.
static void locateTimeAxis(ImPlotTicker& ticker, const ImPlotRange& range, float pixels, bool vertical,
                           ImPlotFormatter formatter, void* data) {
    if (vertical || !(range.Size() > 0.0) || pixels < 1.0f) {
        ImPlot::Locator_Default(ticker, range, pixels, vertical, formatter, data);
        return;
    }
    char buf[IMPLOT_LABEL_MAX_SIZE];
    auto labelW = [&](double v) { formatter(v, buf, sizeof buf, data); return ImGui::CalcTextSize(buf).x; };
    const float  gap     = ImGui::GetFontSize() * 1.5f;
    const double perPx   = range.Size() / pixels;
    double step = ImPlot::NiceNum(perPx * (std::max(labelW(std::round(range.Min)), labelW(std::round(range.Max))) + gap), false);
    // A fractional step adds decimals to every label, so measure real ticks and widen until they fit.
    for (int it = 0; it < 4; ++it) {
        const double t = std::ceil(range.Min / step) * step;
        if (step / perPx >= std::max(labelW(t), labelW(t + step)) + gap) break;
        step = ImPlot::NiceNum(step * 1.01, false);   // next of 1, 2, 5 x 10^k
    }
    const double mant   = step / std::pow(10.0, std::floor(std::log10(step)));   // 1, 2 or 5
    int nMinor = (mant > 1.5 && mant < 3.0) ? 4 : 5;
    // Minor gridlines closer than this read as clutter over the traces; the majors then stand alone.
    if (step / perPx / nMinor < 2.0f * ImGui::GetFontSize()) nMinor = 1;
    for (double k = std::floor(range.Min / step); k * step <= range.Max; k += 1.0) {
        const double major = k * step;   // from an index, so the values don't drift
        if (range.Contains(major)) {
            // A label past the plot's right edge is cut off by the window; half a number reads wrong.
            ImPlotTick& tk = ticker.AddTick(major, true, 0, true, formatter, data);
            if ((major - range.Min) / perPx + 0.5f * tk.LabelSize.x > pixels) tk.ShowLabel = false;
        }
        for (int i = 1; i < nMinor; ++i) {
            const double minor = major + i * step / nMinor;
            if (range.Contains(minor)) ticker.AddTick(minor, false, 0, false, formatter, data);
        }
    }
}
// Every time axis: trimmed-seconds labels, spaced so they don't overlap. Call after SetupAxes.
static void setupTimeAxisX() {
    ImPlot::SetupAxisFormat(ImAxis_X1, fmtTimeAxis);
    ImPlot::GetCurrentPlot()->Axes[ImAxis_X1].Locator = locateTimeAxis;
}

// Warp the OS cursor to the center of the last-submitted ImGui item. Used to keep a stepper button
// under the mouse after a UI-scale change reflows the menu and moves the button, so it stays
// clickable for repeated steps. ImGui and SDL3 window coords are both logical points (no DPI
// conversion); this app is single-window (no multi-viewports) so the main-viewport origin is (0,0).
// (On macOS the warp may be ignored due to cursor-position handling — harmless: the cursor just
// doesn't follow, same as not having the feature.)
static void warpMouseToItemCenter(SDL_Window* window) {
    const ImVec2 mn = ImGui::GetItemRectMin(), mx = ImGui::GetItemRectMax();
    const ImVec2 vp = ImGui::GetMainViewport()->Pos;
    SDL_WarpMouseInWindow(window, 0.5f * (mn.x + mx.x) - vp.x, 0.5f * (mn.y + mx.y) - vp.y);
}

// A stream is a marker/event stream *by default* if it carries string values OR declares its type as
// "Marker"/"Markers" (case-insensitive) — many trigger boxes send integer codes under a "Markers"
// type. The per-stream override (g_streamKind) can flip this either way; see effMarker(). Called once
// per discovery refresh from makeFound (its result is cached in FoundInfo::marker).
static bool isMarkerStream(lsl::stream_info& info) {
    if (info.channel_format() == lsl::cf_string) return true;
    std::string t = info.type();
    for (char& c : t) c = (char)std::tolower((unsigned char)c);
    return t == "marker" || t == "markers";
}

// Stable key for "the user dismissed this stream" bookkeeping: source_id (globally
// unique, stable across reconnects) when set, else uid. Works for any connected source;
// the resolved-stream equivalent is cached in FoundInfo::key below. source_id alone is NOT
// unique: many devices publish their data stream and their marker stream under the SAME
// source_id (e.g. actiCHamp), so the name is folded in to tell them apart — otherwise
// disconnecting/dismissing one would take the other with it. Name is stable across reconnects.
template <class Src>
static std::string streamKeyOf(const Src& s) {
    return !s.sourceId().empty() ? s.sourceId() + "|" + s.name() : s.uid();
}

// Per-stream override of the marker-vs-data classification (keyed by stream key). Present = the user
// explicitly chose (true = marker, false = data); absent = follow the isMarkerStream() default.
// Persisted in imgui.ini; set by the rail's right-click menus. g_reclassifyKey is the pending toggle
// (a stream key) that the connect loop applies next frame by reconnecting the stream as that type.
static std::map<std::string, bool> g_streamKind;
static std::string                 g_reclassifyKey;

// Cached, per-refresh view of a resolved stream. The liblsl stream_info accessors
// (source_id/uid/name/type/...) allocate cross-DLL strings on every call; the resolved set
// only changes at the ~4 Hz discovery refresh, but the rail, autoconnect, and record code
// read this metadata every frame. Compute it once per refresh and read the cache in the loop.
struct FoundInfo {
    lsl::stream_info info;         // live handle (needed to open an inlet on connect)
    std::string key;               // streamKey: source_id+name (disambiguates shared source_id), or uid
    std::string sourceId, uid;
    std::string name, type, hostname;
    int    channels = 0;
    double srate    = 0.0;
    bool   marker       = false;   // type/format default (isMarkerStream); the user override is effMarker()
    bool   stringMarker = false;   // native string stream (cf_string): can't be reclassified as data
};
static FoundInfo makeFound(lsl::stream_info info) {
    FoundInfo f;
    f.sourceId     = info.source_id();
    f.uid          = info.uid();
    f.name         = info.name();
    f.key          = !f.sourceId.empty() ? f.sourceId + "|" + f.name : f.uid;   // name disambiguates shared source_id
    f.type         = info.type();
    f.hostname     = info.hostname();
    f.channels     = info.channel_count();
    f.srate        = info.nominal_srate();
    f.stringMarker = info.channel_format() == lsl::cf_string;
    f.marker       = isMarkerStream(info);   // string-typed OR a "Markers"-typed numeric trigger box
    f.info         = std::move(info);
    return f;
}
// Effective classification: the user's per-stream override if present, else the cached default.
// Reads FoundInfo::marker + g_streamKind, so no per-frame stream_info accessors.
static bool effMarker(const FoundInfo& f) {
    if (!g_streamKind.empty()) {   // common case has no overrides — skip the map lookup
        auto it = g_streamKind.find(f.key);
        if (it != g_streamKind.end()) return it->second;
    }
    return f.marker;
}
// Is this connected source the same resolved stream? Match on (source_id, name) — source_id
// for reconnect stability (a reconnected stream keeps it but gets a new uid), name to separate
// a device's data and marker streams that share a source_id; fall back to uid when there is no
// source_id. Compares cached FoundInfo fields, so no per-frame stream_info accessors/allocations.
template <class Src>
static bool sameStream(const Src& s, const FoundInfo& f) {
    return !f.sourceId.empty() ? (s.sourceId() == f.sourceId && s.name() == f.name)
                               : (s.uid() == f.uid);
}

// BIDS-ish filename templating: substitute {subject}/{session}/{task}/{run}/{acq}/{modality}
// and the built-ins {datetime}/{date}/{time} in `tmpl`. Unknown {keys} are left literal so a
// forgotten field is visible in the resulting name. The template may include subdirectories
// (created at record time).
struct RecVars { std::string subject, session, task, run, acq, modality; };
static std::string resolveTemplate(const std::string& tmpl, const RecVars& v) {
    std::time_t tt = std::time(nullptr); std::tm tm{};
#if defined(_WIN32)
    localtime_s(&tm, &tt);
#else
    localtime_r(&tt, &tm);
#endif
    char dt[32], dd[16], hh[16];
    std::strftime(dt, sizeof(dt), "%Y%m%d_%H%M%S", &tm);
    std::strftime(dd, sizeof(dd), "%Y%m%d", &tm);
    std::strftime(hh, sizeof(hh), "%H%M%S", &tm);
    auto val = [&](const std::string& k) -> std::string {
        if (k == "subject")  return v.subject;
        if (k == "session")  return v.session;
        if (k == "task")     return v.task;
        if (k == "run")      return v.run;
        if (k == "acq")      return v.acq;
        if (k == "modality") return v.modality;
        if (k == "datetime") return dt;
        if (k == "date")     return dd;
        if (k == "time")     return hh;
        return "{" + k + "}";
    };
    std::string out;
    for (std::size_t i = 0; i < tmpl.size();) {
        if (tmpl[i] == '{') {
            const std::size_t e = tmpl.find('}', i);
            if (e != std::string::npos) { out += val(tmpl.substr(i + 1, e - i - 1)); i = e + 1; continue; }
        }
        out += tmpl[i++];
    }
    return out;
}

// A marker event ready to draw: display-time position, text (points into a
// MarkerStreamView that outlives the draw), source color, and a STABLE label row
