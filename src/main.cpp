// Settings and layout are kept apart: a launch restores only the settings (the handler above) and
// drops ImGui's own [Window]/[Docking]/[Table] sections, so every session starts from the default
// layout; a workspace restores only the layout, so loading one for its arrangement can't change
// the theme or recording template. ImGui still writes all sections to imgui.ini (a workspace
// snapshot needs the layout in memory), they are just not read back at launch.
static std::string iniSections(std::string_view ini, bool appSettings) {
    const std::string type = std::string("[") + kSettingsType + "]";
    std::string out;
    bool keep = false;
    while (!ini.empty()) {
        const std::size_t eol = ini.find('\n');
        const std::string_view line = ini.substr(0, eol);
        if (!line.empty() && line[0] == '[') keep = line.starts_with(type) == appSettings;
        if (keep) { out += line; out += '\n'; }
        ini.remove_prefix(eol == std::string_view::npos ? ini.size() : eol + 1);
    }
    return out;
}
